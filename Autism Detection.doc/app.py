def generate_pdf_report(user_name, label, confidence, recommendations, original_img=None):
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4)

    styles = getSampleStyleSheet()
    elements = []

    elements.append(Paragraph("<b>ASD Detection Report</b>", styles["Title"]))
    elements.append(Spacer(1, 20))

    elements.append(Paragraph(f"<b>Name:</b> {user_name or 'User'}", styles["Normal"]))
    elements.append(Paragraph(f"<b>Result:</b> {label}", styles["Normal"]))
    elements.append(Paragraph(f"<b>Confidence:</b> {confidence * 100:.2f}%", styles["Normal"]))
    elements.append(Paragraph(f"<b>Date:</b> {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}", styles["Normal"]))
    elements.append(Spacer(1, 20))

    if original_img is not None:
        pil_img = PILImage.fromarray(original_img)
        img_buffer = io.BytesIO()
        pil_img.save(img_buffer, format="PNG")
        img_buffer.seek(0)

        elements.append(Paragraph("<b>Analyzed Image:</b>", styles["Heading2"]))
        elements.append(Spacer(1, 10))
        elements.append(RLImage(img_buffer, width=250, height=250))
        elements.append(Spacer(1, 20))

    elements.append(Paragraph("<b>Recommendation:</b>", styles["Heading2"]))
    elements.append(Spacer(1, 10))
    elements.append(Paragraph(recommendations, styles["Normal"]))

    elements.append(Spacer(1, 30))
    elements.append(Paragraph("Generated by Autism AI System", styles["Italic"]))

    doc.build(elements)
    buffer.seek(0)

    return buffer

