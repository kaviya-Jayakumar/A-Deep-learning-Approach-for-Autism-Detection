warnings.filterwarnings("ignore")

MODEL_PATH = "autism.h5"

with h5py.File(MODEL_PATH, "r") as f:
    config_data = f.attrs.get("model_config")

    if isinstance(config_data, bytes):
        config = json.loads(config_data.decode("utf-8"))
    else:
        config = json.loads(config_data)

    for layer in config["config"]["layers"]:
        layer_config = layer.get("config", {})

        if "batch_shape" in layer_config:
            layer_config["batch_input_shape"] = layer_config.pop("batch_shape")

        if "dtype" in layer_config:
            layer_config.pop("dtype")

        if "optional" in layer_config:
            layer_config.pop("optional")

        if "quantization_config" in layer_config:
            layer_config.pop("quantization_config")

model = tf.keras.models.model_from_config(config)
model.load_weights(MODEL_PATH, by_name=True, skip_mismatch=True)

CLASS_NAMES = ["ASD Likely", "Not ASD"]

# ================= PREDICTION =================
def predict_image(img):
    img = cv2.cvtColor(np.array(img), cv2.COLOR_RGB2GRAY)
    img = cv2.resize(img, (224, 224))

    img_array = np.expand_dims(img, axis=(0, -1))
    img_array = img_array / 255.0

    preds = model.predict(img_array)
    confidence = float(np.max(preds))
    label = CLASS_NAMES[np.argmax(preds)]

    return label, confidence

# pdf
def generate_pdf_report(user_name, label, confidence, recommendations):
    buffer = io.BytesIO()
    c = canvas.Canvas(buffer, pagesize=A4)
    width, height = A4

    c.setFont("Helvetica-Bold", 16)
    c.drawCentredString(width / 2, height - 80, "ASD Detection Report")

    c.setFont("Helvetica", 12)
    c.drawString(80, height - 130, f"Name: {user_name or 'User'}")
    c.drawString(80, height - 150, f"Result: {label}")
    c.drawString(80, height - 170, f"Confidence: {confidence * 100:.2f}%")

    text = c.beginText(80, height - 210)
    text.textLines(recommendations)
    c.drawText(text)

    c.save()
    buffer.seek(0)
    return buffer

